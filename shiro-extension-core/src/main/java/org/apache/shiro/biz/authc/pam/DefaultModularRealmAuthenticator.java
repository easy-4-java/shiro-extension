package org.apache.shiro.biz.authc.pam;

import org.apache.shiro.authc.AuthenticationException;
import org.apache.shiro.authc.AuthenticationInfo;
import org.apache.shiro.authc.AuthenticationToken;
import org.apache.shiro.authc.pam.ModularRealmAuthenticator;
import org.apache.shiro.realm.Realm;

import java.util.ArrayList;
import java.util.Collection;

public class DefaultModularRealmAuthenticator extends ModularRealmAuthenticator {

    @Override
    protected AuthenticationInfo doAuthenticate(AuthenticationToken authenticationToken)
            throws AuthenticationException {
        assertRealmsConfigured();
        // Snapshot the configured set, not the supporting subset: strategies apply
        // whenever multiple realms are configured, as in ModularRealmAuthenticator.
        Collection<Realm> realms = new ArrayList<>(getRealms());
        if (realms.size() == 1) {
            return doSingleRealmAuthentication(realms.iterator().next(), authenticationToken);
        }
        return doMultiRealmAuthentication(realms, authenticationToken);
    }
}
